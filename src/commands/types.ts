// Emit only binding types backed by the Sites manifest, not an invented runtime ABI.

import fs from "node:fs";
import path from "node:path";
import { CliError, EXIT, usageError } from "../errors.ts";
import { readManifest } from "../manifest.ts";
import { stringOption } from "../util.ts";
import type { DefineCommand } from "../types.ts";

const MARKER = "// Generated by sites types from .openai/hosting.json.\n";

export function registerTypeCommands(define: DefineCommand): void {
  define({
    path: ["types"],
    flags: ["out", "force", "include-runtime"],
    positionals: { min: 0, max: 0 },
    summary: "Generate TypeScript Env declarations for manifest D1/R2 bindings",
    usage: "sites types [--out .openai/types.d.ts] [--force]",
    run: async (ctx) => {
      if (ctx.options["include-runtime"])
        throw usageError(
          "USAGE_RUNTIME_TYPES_UNAVAILABLE",
          "Sites does not expose versioned runtime types.",
          {
            hint: "Use your project's Workers runtime definitions; this command only emits manifest binding declarations.",
          },
        );
      const { manifest } = readManifest(ctx.root);
      const bindings = new Map<string, string>();
      for (const [key, type] of [
        ["d1", "D1Database"],
        ["r2", "R2Bucket"],
      ] as const) {
        const name = manifest[key];
        if (name == null) continue;
        if (typeof name !== "string" || !name.trim())
          throw usageError(
            "USAGE_INVALID_BINDING",
            `Manifest ${key} must be a nonempty binding name.`,
          );
        if (bindings.has(name))
          throw usageError("USAGE_DUPLICATE_BINDING", "D1 and R2 must use distinct binding names.");
        bindings.set(name, type);
      }
      const content =
        MARKER +
        "// Requires your project's Cloudflare Workers runtime type definitions.\n" +
        "export interface Env {\n" +
        [...bindings].map(([name, type]) => `  ${JSON.stringify(name)}: ${type};\n`).join("") +
        "}\n";
      const file = path.resolve(ctx.root, stringOption(ctx.options, "out") ?? ".openai/types.d.ts");
      const previous = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : undefined;
      if (previous !== undefined && !previous.startsWith(MARKER) && !ctx.options.force)
        throw new CliError(
          "CONFLICT_FILE_EXISTS",
          "Refusing to overwrite a file not generated by sites types.",
          {
            exitCode: EXIT.CONFLICT,
            hint: "Choose --out or review the file before using --force.",
          },
        );
      if (content !== previous) {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, content);
      }
      return { data: { path: path.relative(ctx.root, file) } };
    },
  });
}
